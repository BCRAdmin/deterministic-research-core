MAX_REPAIR_ATTEMPTS = 3

BLOCKING_CODES_REQUIRING_REPAIR = {
    "NUMERIC_MISMATCH",
    "PERIOD_MISMATCH",
    "INVALID_TRADE_LEVEL",
    "RATING_TOO_HARSH_FOR_ACTION",
    "RATING_ACTION_MISMATCH",
    "RATING_BLOCKED_BY_DECISION_PACKET",
    "NO_NEWS_WITH_AVAILABLE_SOURCES",
    "OVERSTATED_CAUSALITY",
    "UNVERIFIED_HARD_METRIC",
    "MISSING_EVIDENCE_FOR_HARD_CLAIM",
}


def requires_repair(issue_code: str) -> bool:
    return issue_code in BLOCKING_CODES_REQUIRING_REPAIR
